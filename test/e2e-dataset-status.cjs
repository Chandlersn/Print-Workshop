/** Real UI acceptance for dataset status filters and history deletion. Isolated test data. */
const { app, BrowserWindow, ipcMain } = require('electron')
const fs = require('fs')
const path = require('path')
const assert = require('assert/strict')
const { pathToFileURL } = require('url')
const { rmDeep } = require('./helpers/rm.cjs')
const ROOT = path.resolve(__dirname, '..')
const tmp = fs.mkdtempSync(path.join(__dirname, '.tmp-status-e2e-'))
process.env.PRINTPRESS_DATA_DIR = path.join(tmp, 'data')
app.setPath('userData', path.join(tmp, 'userData'))
app.disableHardwareAcceleration()
app.commandLine.appendSwitch('disable-gpu')
app.commandLine.appendSwitch('in-process-gpu')
app.on('window-all-closed', () => {})
const artifacts = path.join(ROOT, '.workbuddy-ai', 'tmp', 'dataset-status-acceptance')
fs.mkdirSync(artifacts, { recursive: true })
let ui
let checks = 0
const ok = (condition, label) => { assert.ok(condition, label); checks++; console.log('  PASS', label) }
const watchdog = setTimeout(() => { console.error('STATUS_E2E_TIMEOUT'); app.exit(1) }, 60000)
const evaluate = code => ui.webContents.executeJavaScript(code)
async function waitFor(code, label) {
  const start = Date.now()
  while (Date.now() - start < 10000) {
    if (await evaluate(code)) return
    await new Promise(resolve => setTimeout(resolve, 50))
  }
  throw new Error('等待失败：' + label)
}
async function click(selector) {
  await waitFor(`!!document.querySelector(${JSON.stringify(selector)})`, selector)
  const point = await evaluate(`(() => { const el = document.querySelector(${JSON.stringify(selector)}); if (!el) throw new Error('missing ' + ${JSON.stringify(selector)}); el.scrollIntoView({block:'center'}); const r = el.getBoundingClientRect(); return { x: Math.round(r.x+r.width/2), y: Math.round(r.y+r.height/2) } })()`)
  ui.webContents.sendInputEvent({ type: 'mouseDown', button: 'left', clickCount: 1, ...point })
  ui.webContents.sendInputEvent({ type: 'mouseUp', button: 'left', clickCount: 1, ...point })
}
app.whenReady().then(async () => {
  const store = require('../electron/store.cjs')
  const dataset = require('../electron/dataset.cjs')
  const print = require('../electron/print.cjs')
  const csv = path.join(tmp, 'people.csv')
  fs.writeFileSync(csv, '姓名\n张三\n', 'utf8')
  const base = dataset.getDataset(dataset.importFromFile(csv).id)
  const originals = []
  for (let i = 0; i < 7; i++) originals.push({ ...base, id: `ds_status_${i}`, name: `名单${i}`, printCount: i === 1 ? 1 : 0, lastPrintedAt: i === 1 ? new Date().toISOString() : '', source: { ...base.source, batchId: i < 3 ? 'batch_a' : 'batch_b', fileName: i < 3 ? '第一批' : '第二批' } })
  store.saveJson('datasets', originals)
  store.saveJson('settings', { onboarded: true })
  require('../electron/ipc.cjs').registerIpc()
  ipcMain.handle('app:meta', () => ({ version: '0.6.0-test', links: {} }))
  ui = new BrowserWindow({ show: false, width: 1320, height: 950, webPreferences: { preload: path.join(ROOT, 'electron/preload.cjs'), sandbox: false, contextIsolation: true, offscreen: true, backgroundThrottling: false } })
  await ui.loadURL(pathToFileURL(path.join(ROOT, 'dist/index.html')).href)
  await waitFor(`document.querySelectorAll('.ds-item').length===3`, '第一批名单')
  ok(await evaluate(`document.querySelector('[data-print-status="printed"]').textContent.includes('1') && document.querySelector('[data-print-status="unprinted"]').textContent.includes('2')`), '筛选按钮显示当前批次已打1、未打2')
  await click('[data-print-status="printed"]')
  await waitFor(`document.querySelectorAll('.ds-item').length===1 && document.querySelector('.detail-title')?.textContent==='名单1'`, '已打名单及详情')
  ok(true, '已打筛选只显示成功全量出片名单，详情跟随')
  fs.writeFileSync(path.join(artifacts, 'printed-filter.png'), (await ui.webContents.capturePage()).toPNG())
  await click('[data-print-status="unprinted"]')
  await waitFor(`document.querySelectorAll('.ds-item').length===2 && document.querySelector('.detail-title')?.textContent==='名单0'`, '未打名单')
  ok(true, '未打筛选排除已打名单，并切换到可见详情')
  await evaluate(`(() => { const el=document.querySelector('.ds-search'); el.value='名单2'; el.dispatchEvent(new Event('input',{bubbles:true})); })()`)
  await waitFor(`document.querySelectorAll('.ds-item').length===1 && document.querySelector('.detail-title')?.textContent==='名单2'`, '搜索叠加')
  ok(true, '搜索与打印状态筛选叠加生效')
  await click('[data-print-status="printed"]')
  await waitFor(`!!document.querySelector('.ds-none') && !document.querySelector('.ds-detail')`, '空筛选结果')
  ok(true, '空结果显示提示，旧详情不会留在页面被误操作')
  await evaluate(`(() => { const el=document.querySelector('.ds-search'); el.value=''; el.dispatchEvent(new Event('input',{bubbles:true})); const batch=document.querySelector('.batch-select'); batch.value='batch_b'; batch.dispatchEvent(new Event('change',{bubbles:true})); })()`)
  await waitFor(`document.querySelector('[data-print-status="unprinted"]').textContent.includes('4') && !!document.querySelector('.ds-none')`, '切换批次')
  await click('[data-print-status="unprinted"]')
  await waitFor(`document.querySelectorAll('.ds-item').length===4 && document.querySelector('.detail-title')?.textContent==='名单3'`, '新批次未打列表')
  ok(true, '切换批次后保留筛选并刷新计数，选择新批次名单')

  const job = print.createJob({ datasetId: originals[1].id, datasetName: originals[1].name, templateName: '删除验收', status: 'ok', recordCount: 1, snapshotHtml: '<html>archive</html>' })
  const jobDir = path.join(process.env.PRINTPRESS_DATA_DIR, path.dirname(job.snapshot))
  fs.mkdirSync(path.join(jobDir, 'photos'))
  fs.writeFileSync(path.join(jobDir, 'photos', 'copy.jpg'), 'PHOTO COPY')
  await evaluate(`document.querySelectorAll('.nav-label')[4].click()`)
  await click('.history-trigger')
  await waitFor(`!!document.querySelector('.job-del')`, '打印历史')
  await click('.job-del')
  ok(await evaluate(`document.querySelector('.cd-msg').textContent.includes('PDF') && document.querySelector('.cd-msg').textContent.includes('归档照片副本')`), '删除确认明确照片副本与保留数据')
  const originalRm = fs.rmSync
  try {
    fs.rmSync = function(target, options) { if (target===jobDir) throw new Error('验收：文件占用'); return originalRm.call(fs,target,options) }
    await click('.cd-btn.danger')
    await waitFor(`document.body.textContent.includes('删除失败')`, '删除失败提示')
    ok(print.listJobs().some(j => j.id === job.id) && fs.existsSync(jobDir) && await evaluate(`!!document.querySelector('.job-del')`), '清理失败真实界面提示失败，记录和归档均保留')
  } finally { fs.rmSync = originalRm }
  await click('.job-del')
  await click('.cd-btn.danger')
  await waitFor(`!document.querySelector('.job-del') && document.body.textContent.includes('已删除该打印记录及归档件')`, '删除成功')
  ok(!fs.existsSync(jobDir) && print.listJobs().length===0 && JSON.parse(fs.readFileSync(path.join(process.env.PRINTPRESS_DATA_DIR, 'print-jobs.json.bak'), 'utf8')).length===0, '真实删除释放快照照片目录、主索引和恢复备份记录')
  await evaluate(`document.querySelectorAll('.nav-label')[0].click()`)
  await waitFor(`document.querySelectorAll('.ds-item').length>0`, '返回数据页')
  await evaluate(`(() => { const el=document.querySelector('.batch-select'); el.value='batch_a'; el.dispatchEvent(new Event('change',{bubbles:true})); })()`)
  await click('[data-print-status="printed"]')
  await waitFor(`document.querySelectorAll('.ds-item').length===1 && document.querySelector('.ds-name').textContent==='名单1'`, '已打状态仍在')
  ok(dataset.getDataset(originals[1].id).printCount===1, '删除历史后已打筛选仍显示累计打印状态')
  fs.writeFileSync(path.join(artifacts, 'result.json'), JSON.stringify({ ok: true, checks }, null, 2))
  console.log('STATUS_E2E_OK', checks)
  clearTimeout(watchdog)
  ui.destroy()
  try { rmDeep(tmp) } catch { /* Electron can hold userData caches until exit. Isolated tmp remains. */ }
  app.exit(0)
}).catch(err => { console.error('STATUS_E2E_FAIL', err.stack); clearTimeout(watchdog); if(ui&&!ui.isDestroyed())ui.destroy(); try { rmDeep(tmp) } catch {} app.exit(1) })
