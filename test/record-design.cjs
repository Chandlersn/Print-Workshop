const assert = require('assert/strict'), fs = require('fs'), path = require('path')
const tmp = fs.mkdtempSync(path.join(__dirname, '.tmp-record-design-'))
process.env.PRINTPRESS_DATA_DIR = path.join(tmp, 'data')
const store = require('../electron/store.cjs'), designs = require('../electron/designs.cjs')
const templates = require('../electron/templates.cjs'), dataset = require('../electron/dataset.cjs')
const records = require('../electron/record-designs.cjs'), print = require('../electron/print.cjs')
const overrides = require('../electron/photo-overrides.cjs')

async function main() {
store.saveJson('datasets', [{id:'ds_record',name:'名单',photoMatchColumn:'photo',columns:[{key:'name',alias:'姓名',printOn:true},{key:'photo',alias:'照片',printOn:false}],rows:[{name:'甲',photo:'a'},{name:'乙',photo:'a'}]}])
const img = designs.importImageBuffer(fs.readFileSync(path.join(__dirname, 'fixtures/tiny.png')), '照片.png', 'photo')
store.saveJson('photo-bindings', [{datasetId:'ds_record',column:'photo',files:[{name:'a.png',assetId:img.id}]}])
const base = designs.saveDesign({name:'共用底图',artboard:{w:90,h:60},layers:[{id:'title',type:'text',text:'公共标题',x:2,y:2,w:40,h:10},{id:'portrait',type:'image',variable:true,bindColumn:'photo',x:10,y:15,w:30,h:40,fit:'contain'}]})
const tpl = templates.saveTemplate({name:'海报',datasetId:'ds_record',pageSize:{id:'custom',w:90,h:60},fields:[{column:'name',x:55,y:50,fontSize:16}],backgroundDesign:{id:base.id,revision:base.revision}})
const ds = dataset.getDataset('ds_record'), key = {datasetId:ds.id,templateId:tpl.id,rowId:ds.recordIds[0]}
const separateDoc = structuredClone(base); delete separateDoc.id; separateDoc.revision=0
const separated = designs.saveDesign(separateDoc,{recordOwner:key})
assert.ok(fs.existsSync(path.join(process.env.PRINTPRESS_DATA_DIR,'individual-designs',separated.id,'1.json')))
assert.equal(designs.getDesign(separated.id,1).name,separated.name)
const separatedNext = designs.saveDesign({...separated,name:'单人第二版'},{recordOwner:key})
assert.equal(designs.getDesign(separated.id,1).name,separated.name, '独立工程保留历史版本')
assert.equal(designs.getDesign(separated.id,2).name,separatedNext.name)
assert.throws(()=>designs.saveDesign(separatedNext,{recordOwner:{...key,rowId:ds.recordIds[1]}}),/其他人员|独立底图/)
designs.deleteDesign(separated.id)
assert.ok(designs.purgeOrphanDirs().removed.includes(separated.id), '可安全清理删除的单人工程残留')
const frameKey = {...key,layerId:'portrait'}
overrides.set({...frameKey,fit:'cover',focal:{x:.2,y:.7},position:{x:13,y:21},size:{w:35,h:42}})
const request = records.get(key)
assert.equal(request.hasOverride,false)
assert.deepEqual(request.photoStyles.portrait,{fit:'cover',focal:{x:.2,y:.7},position:{x:13,y:21},size:{w:35,h:42}})
let pre = print.buildBatchHtml(ds.id,tpl.id,null,{encodeDerivatives:false})
assert.equal((pre.html.match(/left:13mm;top:21mm/g)||[]).length,1, '单人照片位置只应用一次')
assert.ok(pre.html.includes('left:13mm;top:21mm;width:35mm;height:42mm'), '单人照片的宽高进入实际输出')
assert.ok(pre.snapshotHtml.includes('left:13mm;top:21mm'), '归档保留单人照片位置')
assert.throws(()=>overrides.set({...frameKey,fit:'cover',focal:{x:.5,y:.5},position:{x:NaN,y:0}}),/位置/)
assert.throws(()=>overrides.set({...frameKey,fit:'cover',focal:{x:.5,y:.5},size:{w:0,h:10}}),/大小/)
const clone = structuredClone(base); delete clone.id; clone.revision=0; clone.name='甲的底图'; clone.layers.find(l=>l.id==='title').text='只给甲的标题'
const portrait = clone.layers.find(l=>l.id==='portrait'); portrait.fit='contain'; portrait.focal={x:.8,y:.4}
const variant = designs.saveDesign(clone)
dataset.updateCell(ds.id,0,'photo','temporarily-changed')
assert.throws(()=>records.set({...key,baseKey:request.baseKey,photoRevision:request.photoRevision,recordRevision:request.recordRevision,overrideRevision:request.overrideRevision,designRef:{id:variant.id,revision:variant.revision}}),/数据或照片已变化/)
dataset.updateCell(ds.id,0,'photo','a')
const saved = records.set({...key,baseKey:request.baseKey,photoRevision:request.photoRevision,recordRevision:request.recordRevision,overrideRevision:request.overrideRevision,designRef:{id:variant.id,revision:variant.revision}})
assert.throws(()=>records.set({...key,baseKey:request.baseKey,photoRevision:request.photoRevision,recordRevision:request.recordRevision,overrideRevision:request.overrideRevision,designRef:saved.designRef}),/底图已被其他操作更新/)
assert.equal(records.get(key).hasOverride,true)
assert.throws(()=>designs.deleteDesign(variant.id),/单人海报/)
let built = print.buildBatchHtml(ds.id,tpl.id,null,{encodeDerivatives:false})
const pages = [...built.html.matchAll(/<div class="page">([\s\S]*?)(?=<div class="page">|\n<\/body>)/g)].map(item=>item[1])
assert.equal(pages.length,2)
assert.ok(pages[0].includes('只给甲的标题') && !pages[0].includes('公共标题'))
assert.ok(pages[1].includes('公共标题') && !pages[1].includes('只给甲的标题'))
assert.ok(pages[0].includes('object-fit:contain;object-position:80% 40%'), '旧照片焦点已融入独立底图，不覆盖编辑后的图框')
assert.ok(built.snapshotHtml.includes('只给甲的标题') && built.snapshotHtml.includes('公共标题'))
assert.ok(print.buildBatchHtml(ds.id,tpl.id,null,{previewPage:1,encodeDerivatives:false}).html.includes('公共标题'))
assert.ok(!print.buildBatchHtml(ds.id,tpl.id,[1],{encodeDerivatives:false}).html.includes('只给甲的标题'))
assert.ok(print.buildBatchHtml(ds.id,tpl.id,null,{range:{from:0,to:1},encodeDerivatives:false}).html.includes('只给甲的标题'))
assert.ok(!print.buildBatchHtml(ds.id,tpl.id,null,{range:{from:1,to:2},encodeDerivatives:false}).html.includes('只给甲的标题'), '分批出片按人员稳定选择底图')
overrides.set({...frameKey,fit:'cover',focal:{x:.35,y:.65},position:{x:20,y:22},size:{w:40,h:44}})
built=print.buildBatchHtml(ds.id,tpl.id,[0],{encodeDerivatives:false})
assert.ok(built.html.includes('object-fit:cover;object-position:35% 65%'), '保存底图后新调整的取景仍然生效')
assert.ok(built.html.includes('left:20mm;top:22mm;width:40mm;height:44mm'), '保存单人底图后的位置和大小调整作用于该独立底图')
assert.deepEqual(overrides.inspect(frameKey).position,{x:20,y:22})
const beforeFrameChange = records.get(key)
assert.throws(()=>records.set({...key,baseKey:beforeFrameChange.baseKey,photoRevision:request.photoRevision,recordRevision:beforeFrameChange.recordRevision,overrideRevision:beforeFrameChange.overrideRevision,designRef:saved.designRef}),/取景已变化/)
dataset.updateCell(ds.id,0,'photo','missing')
const nextRequest = records.get(key), noPhoto = designs.getDesign(variant.id,variant.revision)
noPhoto.layers = noPhoto.layers.filter(layer=>layer.id!=='portrait')
const noPhotoSaved = designs.saveDesign(noPhoto)
records.set({...key,baseKey:nextRequest.baseKey,photoRevision:nextRequest.photoRevision,recordRevision:nextRequest.recordRevision,overrideRevision:nextRequest.overrideRevision,designRef:{id:noPhotoSaved.id,revision:noPhotoSaved.revision}})
built = print.buildBatchHtml(ds.id,tpl.id,null,{encodeDerivatives:false})
assert.ok(built.html.includes('只给甲的标题') && (built.html.match(/data-photo-column=/g)||[]).length === 1, '移除了变量图框的单人底图不要求此人有照片')
const check = await print.photoPreflight(ds.id,tpl.id)
assert.equal(check.photoFrameCount, 1)
assert.equal(check.canOutput, true, '无照片图框的单人海报不会被照片校验错误阻断')
for (const [mode, pageSize, layout] of [
  ['grid',{id:'custom',w:180,h:60},{mode:'grid',itemW:90,itemH:60}],
  ['fold',{id:'custom',w:90,h:120},{mode:'fold'}],
]) {
  const otherTpl = templates.saveTemplate({name:`${mode} 海报`,datasetId:ds.id,pageSize,layout,fields:[{column:'name',x:55,y:50,fontSize:16}],backgroundDesign:{id:base.id,revision:base.revision}})
  const otherKey = {datasetId:ds.id,templateId:otherTpl.id,rowId:ds.recordIds[1]}, info = records.get(otherKey)
  const copy = structuredClone(base); delete copy.id; copy.revision=0; copy.layers.find(layer=>layer.id==='title').text=`${mode} 单人标题`
  const otherDesign = designs.saveDesign(copy)
  records.set({...otherKey,baseKey:info.baseKey,photoRevision:info.photoRevision,recordRevision:info.recordRevision,overrideRevision:info.overrideRevision,designRef:{id:otherDesign.id,revision:otherDesign.revision}})
  overrides.set({...otherKey,layerId:'portrait',fit:'cover',focal:{x:.5,y:.5},position:{x:14,y:17},size:{w:32,h:38}})
  const rendered = print.buildBatchHtml(ds.id,otherTpl.id,null,{encodeDerivatives:false})
  assert.equal((rendered.html.match(new RegExp(`${mode} 单人标题`,'g'))||[]).length, mode==='fold' ? 2 : 1, `${mode} 只渲染指定人员的独立底图`)
  assert.ok(rendered.snapshotHtml.includes(`${mode} 单人标题`))
  assert.equal((rendered.html.match(/left:14mm;top:17mm;width:32mm;height:38mm/g)||[]).length, mode==='fold' ? 2 : 1, `${mode} 输出按人员使用位置和大小`)
}
const pinnedTpl = templates.saveTemplate({name:'引用保护',datasetId:ds.id,pageSize:{id:'custom',w:90,h:60},fields:[{column:'name',x:55,y:50,fontSize:16}],backgroundDesign:{id:base.id,revision:base.revision}})
const pinnedKey = {datasetId:ds.id,templateId:pinnedTpl.id,rowId:ds.recordIds[1]}, pinnedInfo = records.get(pinnedKey)
const pixels = new Uint8ClampedArray(4*4*4).fill(111)
const uniqueAsset = designs.importImageBuffer(require('../electron/psd-import.cjs').pngFromPixels({width:4,height:4,data:pixels}),'独立图.png','ephemeral')
const pinnedCopy = structuredClone(base); delete pinnedCopy.id; pinnedCopy.revision=0; pinnedCopy.assets[uniqueAsset.id]=uniqueAsset
pinnedCopy.layers.push({id:'fixed',type:'image',assetId:uniqueAsset.id,x:1,y:1,w:5,h:5})
const pinnedDesign = designs.saveDesign(pinnedCopy)
records.set({...pinnedKey,baseKey:pinnedInfo.baseKey,photoRevision:pinnedInfo.photoRevision,recordRevision:pinnedInfo.recordRevision,overrideRevision:pinnedInfo.overrideRevision,designRef:{id:pinnedDesign.id,revision:pinnedDesign.revision}})
const newer = structuredClone(pinnedDesign); newer.layers = newer.layers.filter(layer=>layer.id!=='fixed'); delete newer.assets[uniqueAsset.id]; designs.saveDesign(newer)
assert.ok(require('../electron/asset-library.cjs').referencedAssetIds().has(uniqueAsset.id), '固定的单人历史版本仍保护它的素材')
records.clear(pinnedKey)
assert.ok(!require('../electron/asset-library.cjs').referencedAssetIds().has(uniqueAsset.id), '恢复默认后不再保留该独立素材引用')
const list=store.loadJson('templates'); list.find(item=>item.id===tpl.id).pageSize={id:'custom',w:100,h:60}; store.saveJson('templates',list)
assert.throws(()=>print.buildBatchHtml(ds.id,tpl.id,[0]),/不一致|已变化/)
assert.equal(records.get(key).stale,true)
assert.equal(records.clear(key).removed,true)
designs.deleteDesign(variant.id)
const gridTpl = store.loadJson('templates').find(item=>item.name==='grid 海报')
templates.deleteTemplate(gridTpl.id)
assert.ok(!(store.loadJson('record-designs')||[]).some(item=>item.templateId===gridTpl.id), '删除模板会解除单人底图引用')
dataset.deleteRow(ds.id,1)
assert.ok(!(store.loadJson('record-designs')||[]).some(item=>item.rowId===ds.recordIds[1]), '删除人员会解除对应单人底图引用')
console.log('ok - 单人底图隔离、打印与归档、焦点交互、版本冲突和恢复默认')
}
main().catch(error => { console.error(error); process.exitCode = 1 })
