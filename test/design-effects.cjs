const assert = require('node:assert/strict')
const { normalizeDesign, renderDesign, linearEndpoints, shadowRegion, SCHEMA_VERSIONS } = require('../electron/design-layout.cjs')

const base = { schemaVersion: 1, name: 'gradient test', artboard: { w: 210, h: 148 }, assets: {}, layers: [] }
const paint = { type: 'linear', angle: 0, stops: [{ offset: 1, color: '#000000', opacity: 0.5 }, { offset: 0, color: '#ffffff', opacity: 1 }] }
const doc = normalizeDesign({ ...base, artboard: { ...base.artboard, backgroundPaint: paint }, layers: [{ id: 'box', type: 'rect', x: 10, y: 10, w: 80, h: 40, fillPaint: paint }] })
assert.equal(doc.schemaVersion, 4)
assert.deepEqual(doc.artboard.backgroundPaint.stops.map(s => s.offset), [0, 1])
assert.deepEqual(linearEndpoints(100, 50, 0), { x1: 0, y1: 25, x2: 100, y2: 25 })
const first = renderDesign(doc)
const second = renderDesign(doc)
const ids = [...first.html.matchAll(/id="(pp_effect_[^"]+)"/g)].map(match => match[1])
assert.equal(ids.length, 2)
assert.equal(new Set(ids).size, ids.length)
assert.ok(first.html.includes('color-interpolation="sRGB"'))
assert.ok(first.html.includes('stop-opacity="0.5"'))
assert.notEqual(first.html.match(/id="(pp_effect_[^"]+)"/)[1], second.html.match(/id="(pp_effect_[^"]+)"/)[1])
assert.throws(() => normalizeDesign({ ...base, artboard: { ...base.artboard, backgroundPaint: { ...paint, stops: [{ offset: 0.2, color: '#fff' }, { offset: 1, color: '#000' }] } } }), /首尾/)
assert.throws(() => normalizeDesign({ ...base, layers: [{ id: 'line', type: 'line', fillPaint: paint }] }), /仅支持/)
// 取「已支持的最大版本 + 1」探测更高版本被拒，别写死数字（写死会随抬版本变假失败）。
assert.throws(() => normalizeDesign({ ...base, schemaVersion: Math.max(...SCHEMA_VERSIONS) + 1 }), /版本/)
const shadow = { dxMm: -3, dyMm: 4, blurMm: 2, color: '#112233', opacity: 0.35 }
const withShadow = normalizeDesign({ ...base, layers: [{ id: 'shadow-box', type: 'rect', x: 5, y: 5, w: 30, h: 12, fillPaint: paint, shadow }] })
assert.equal(withShadow.schemaVersion, 4)
assert.deepEqual(withShadow.layers[0].shadow, shadow)
assert.deepEqual(shadowRegion(30, 12, shadow), { x: -11.25, y: -8.25, width: 49.5, height: 32.5 })
const shadowOutput = renderDesign(withShadow)
assert.match(shadowOutput.html, /filterUnits="userSpaceOnUse" primitiveUnits="userSpaceOnUse" color-interpolation-filters="sRGB"/)
assert.match(shadowOutput.html, /feGaussianBlur in="SourceAlpha" stdDeviation="2"/)
assert.match(shadowOutput.html, /feComposite in="color" in2="shift" operator="in"/)
assert.match(shadowOutput.html, /overflow:visible/)
assert.equal((shadowOutput.html.match(/<rect /g) || []).length, 2, '阴影仅复制形状，主体保持独立')
assert.throws(() => normalizeDesign({ ...base, layers: [{ id: 'bad', type: 'line', shadow }] }), /阴影仅支持/)
assert.throws(() => normalizeDesign({ ...base, layers: [{ id: 'bad', type: 'rect', shadow: { ...shadow, blurMm: 11 } }] }), /阴影模糊/)
assert.throws(() => normalizeDesign({ ...base, layers: [{ id: 'bad', type: 'rect', shadow: { ...shadow, color: 'url(#evil)' } }] }), /颜色/)
console.log('底图渐变与阴影领域验收通过')
