const { app, BrowserWindow } = require('electron')
const fs = require('fs')
const path = require('path')
const assert = require('assert/strict')
const { pathToFileURL } = require('url')
const { rmDeep } = require('./helpers/rm.cjs')
const root = path.resolve(__dirname, '..')
const tmp = fs.mkdtempSync(path.join(__dirname, '.tmp-code-ui-'))
process.env.PRINTPRESS_DATA_DIR = path.join(tmp, 'data')
app.setPath('userData', path.join(tmp, 'userData'))
app.disableHardwareAcceleration()
app.commandLine.appendSwitch('disable-gpu')
app.commandLine.appendSwitch('in-process-gpu')
app.on('window-all-closed', () => {})
let win
const watchdog = setTimeout(() => { console.error('CODE_UI_TIMEOUT'); app.exit(1) }, 45000)
const evaluate = async code => { try { return await win.webContents.executeJavaScript(code) } catch (err) { console.error('FAILED EXPRESSION:', code); throw err } }
async function waitFor(code) {
  const deadline = Date.now() + 10000
  while (Date.now() < deadline) {
    if (await evaluate(code)) return
    await new Promise(resolve => setTimeout(resolve, 50))
  }
  throw new Error('等待失败：' + code)
}
app.whenReady().then(async () => {
  const dataset = require('../electron/dataset.cjs')
  const store = require('../electron/store.cjs')
  const csv = path.join(tmp, 'people.csv')
  fs.writeFileSync(csv, '姓名\n甲\n乙\n丙\n丁\n')
  const { id } = dataset.importFromFile(csv)
  store.saveJson('settings', { onboarded: true })
  require('../electron/ipc.cjs').registerIpc()
  require('electron').ipcMain.handle('app:meta', () => ({ version: 'test', links: {} }))
  win = new BrowserWindow({ show: false, width: 1200, height: 900, webPreferences: { preload: path.join(root, 'electron/preload.cjs'), sandbox: false, contextIsolation: true, offscreen: true, backgroundThrottling: false } })
  await win.loadURL(pathToFileURL(path.join(root, 'dist/index.html')).href)
  await waitFor(`Array.from(document.querySelectorAll('button')).some(b => b.textContent.trim() === '生成编码')`)
  console.log('UI loaded')
  await evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent.trim() === '生成编码').click()`)
  await waitFor(`!!document.querySelector('[aria-labelledby="code-title"] input')`)
  assert.equal(await evaluate(`document.activeElement === document.querySelector('[aria-labelledby="code-title"] input')`), true)
  assert.equal(await evaluate(`document.querySelector('.random-tool input').value`), '6')
  await waitFor(`document.querySelector('.preview')?.textContent.includes('证书-')`)
  assert.equal(await evaluate(`document.querySelectorAll('.preview > div').length`), 3)
  assert.equal(dataset.getDataset(id).columns.length, 1, '预览不写入数据')
  for (const length of [17, 8]) {
    await evaluate(`(() => { const el = document.querySelector('.random-tool input'); el.value = '${length}'; el.dispatchEvent(new Event('input', { bubbles: true })) })()`)
    assert.equal(await evaluate(`document.querySelector('.random-tool button').disabled`), length === 17)
  }
  await evaluate(`document.querySelector('.random-tool button').click()`)
  assert.ok(await evaluate(`document.querySelector('[data-dialog-initial]').value.includes('{随机:8}')`))
  await waitFor(`/0001[0-9A-Z]{8}$/.test(document.querySelector('.preview > div')?.textContent || '')`)
  assert.equal(await evaluate(`document.querySelector('.code-tools').lastElementChild.textContent.trim()`), '＋ 流水号')
  await evaluate(`(() => {
    const rule = document.querySelector('[data-dialog-initial]')
    const date = rule.value.indexOf('{日期}')
    rule.setSelectionRange(date, date + 4)
    rule.dispatchEvent(new Event('select'))
    document.querySelector('.picker > button').click()
  })()`)
  await waitFor(`!!document.querySelector('[aria-label="年份"]')`)
  await evaluate(`(() => {
    const year = document.querySelector('[aria-label="年份"]')
    year.value = '2028'
    year.dispatchEvent(new Event('input', {bubbles: true}))
    const month = document.querySelector('[aria-label="月份"]')
    month.value = '2'
    month.dispatchEvent(new Event('change', {bubbles: true}))
  })()`)
  await evaluate(`document.querySelector('[aria-label="2028年2月29日"]').click()`)
  await waitFor(`document.querySelector('.preview')?.textContent.includes('证书-20280229-0001')`)
  await evaluate(`(() => { const input = document.querySelector('[aria-labelledby="code-title"] input'); input.value = 'AB'; input.dispatchEvent(new Event('input', { bubbles: true })); input.setSelectionRange(1, 1); input.dispatchEvent(new Event('select', { bubbles: true })); Array.from(document.querySelectorAll('[aria-labelledby="code-title"] button')).find(b => b.textContent.includes('流水号')).click(); })()`)
  assert.equal(await evaluate(`document.querySelector('[aria-labelledby="code-title"] input').value`), 'A{流水号}B')
  await waitFor(`document.querySelector('.preview')?.textContent.includes('A0001B')`)
  await evaluate(`Array.from(document.querySelectorAll('[aria-labelledby="code-title"] button')).find(b => b.textContent.trim() === '确认写入').click()`)
  await waitFor(`document.querySelector('.code-result')?.textContent.includes('4 条')`)
  await waitFor(`Array.from(document.querySelectorAll('button')).some(b => b.textContent.trim() === '生成编码')`)
  assert.deepEqual(dataset.getDataset(id).rows.map(r => r[dataset.getDataset(id).columns[1].key]), ['A0001B', 'A0002B', 'A0003B', 'A0004B'])
  await evaluate(`Array.from(document.querySelectorAll('button')).find(b => b.textContent.trim() === '生成编码').click()`)
  await waitFor(`!!document.querySelector('[aria-labelledby="code-title"]')`)
  await evaluate(`document.querySelector('[aria-labelledby="code-title"]').dispatchEvent(new KeyboardEvent('keydown', {key:'Escape', bubbles:true}))`)
  await waitFor(`!document.querySelector('[aria-labelledby="code-title"]')`)
  await evaluate(`document.querySelector('.edit-grid td[data-ri="0"][data-ck="姓名"]').click()`)
  await waitFor(`!!document.querySelector('.cell-input')`)
  await evaluate(`(() => { const input = document.querySelector('.cell-input'); input.value = '修改中'; input.dispatchEvent(new Event('input', {bubbles:true})); input.click() })()`)
  assert.equal(await evaluate(`document.querySelector('.cell-input').value`), '修改中', '点击正在编辑的单元格不应重置输入')
  await evaluate(`Array.from(document.querySelectorAll('.nav-item')).find(b => b.textContent.includes('打印中心')).click()`)
  await waitFor(`Array.from(document.querySelectorAll('.nav-item')).find(b => b.textContent.includes('打印中心')).classList.contains('active')`)
  assert.equal(dataset.getDataset(id).rows[0]['姓名'], '修改中', '切换页面前应保存正在编辑的数据')
  console.log('code generator UI tests passed')
  clearTimeout(watchdog); win.destroy(); try { rmDeep(tmp) } catch {} app.exit(0)
}).catch(error => { console.error(error); clearTimeout(watchdog); if (win) win.destroy(); try { rmDeep(tmp) } catch {} app.exit(1) })
