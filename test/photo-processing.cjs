const assert = require('assert/strict'), fs = require('fs'), path = require('path')
const tmp = fs.mkdtempSync(path.join(__dirname, '.tmp-photo-processing-'))
process.env.PRINTPRESS_DATA_DIR = path.join(tmp, 'data')
const { normalizeRecipe, processPixels, orientedRgba, photoTransform } = require('../electron/photo-processing-pixels.cjs')
const { pngFromPixels } = require('../electron/psd-import.cjs')
const width = 64, height = 64, data = new Uint8ClampedArray(width * height * 4)
for (let i = 0; i < data.length; i += 4) data.set([30, 120, 210, 255], i)
const image = { width, height, data }
const basic = normalizeRecipe({ width, height })
assert.deepEqual(processPixels(image, basic).data, data, '无效果的同尺寸处理不能改变像素')
const feathered = processPixels(image, { ...basic, edge: true, edgeWidth: .2, edgeOpacity: .5, bottom: true, bottomStart: .5, bottomOpacity: 0 })
assert.equal(feathered.data[(32 * 64 + 32) * 4 + 3], 255, '中心主体保持不透明')
assert.equal(feathered.data[(0 * 64 + 32) * 4 + 3], 128, '外缘不透明度可为 50%')
assert.equal(feathered.data[(63 * 64 + 32) * 4 + 3], 0, '底部渐隐可叠加并达到透明')
assert.equal(data[(63 * 64 + 32) * 4 + 3], 255, '不修改原像素')
const padded = processPixels({ width:64,height:32,data:data.slice(0,64*32*4) }, { ...basic, bottom:true, bottomStart:.5, bottomOpacity:0 })
assert.equal(padded.data[(47*64+32)*4+3], 0, '完整显示有上下留白时，渐隐仍到达照片可见内容的底部')
assert.equal(padded.data[(24*64+32)*4+3], 255, '留白适配后的主体上半部保持不透明')
const contour = new Uint8ClampedArray(data)
for (let y = 0; y < 64; y++) for (let x = 0; x < 64; x++) if (x < 12 || x > 51 || y < 12 || y > 51) contour[(y * 64 + x) * 4 + 3] = 0
const shaped = processPixels({ width, height, data: contour }, { ...basic, edge: true, edgeTarget: 'subject', edgeWidth: .2, edgeOpacity: .5 })
assert.equal(shaped.data[(32 * 64 + 32) * 4 + 3], 255)
assert.ok(shaped.data[(32 * 64 + 12) * 4 + 3] < 140, '人物轮廓羽化根据主体边缘，而不是只看照片外框')
const oriented = orientedRgba(Buffer.from([0, 0, 255, 255, 255, 0, 0, 255]), 2, 1, 6)
assert.equal(oriented.width, 1); assert.equal(oriented.height, 2)
assert.deepEqual([...oriented.data], [255, 0, 0, 255, 0, 0, 255, 255], 'EXIF 旋转和 BGRA 颜色通道正确')
for (const invalid of [{ width: -1 }, { height: 9000 }, { fit: 'stretch' }, { scale: NaN }, { bottomStart: 1 }, { edgeTarget: 'unknown' }]) assert.throws(() => normalizeRecipe(invalid))
console.log('ok - 适配、透明蒙版、轮廓羽化、原件隔离和 EXIF 像素变换')
const alignRecipe = normalizeRecipe({ width: 64, height: 64, faceAlign: true, faceHeight: .3, eyeY: .32 })
const face = { x: 12, y: 10, w: 24, h: 30, eyes: [{ x: 18, y: 22 }, { x: 30, y: 22 }] }
const aligned = photoTransform(image, alignRecipe, [face])
assert.ok(Math.abs(face.h * aligned.factor - 64 * .3) < 1e-6)
assert.ok(Math.abs(22 * aligned.factor + aligned.top - 64 * .32) < 1e-6)
assert.ok(Math.abs(24 * aligned.factor + aligned.left - 32) < 1e-6)
assert.ok(photoTransform(image, alignRecipe, []).issues.includes('no-face'))
assert.ok(photoTransform(image, alignRecipe, [face, face]).issues.includes('multiple-faces'))
console.log('ok - 人物大小和眼睛高度按同一目标对齐，无人脸与多人必须标记复核')

;(async () => {
  const store = require('../electron/store.cjs'), designs = require('../electron/designs.cjs'), processing = require('../electron/photo-processing.cjs'), photos = require('../electron/photo-library.cjs')
  const a = designs.importImageBuffer(pngFromPixels(image), 'a.png', 'managed')
  const second = new Uint8ClampedArray(data); second[0] = 70
  const b = designs.importImageBuffer(pngFromPixels({ width, height, data: second }), 'b.png', 'managed')
  store.saveJson('datasets', [{ id: 'ds_processing', name: '自动照片', photoMatchColumn: 'photo', columns: [{ key: 'photo' }], rows: [{ photo: 'a' }, { photo: 'a' }, { photo: 'b' }] }])
  store.saveJson('photo-bindings', [{ datasetId: 'ds_processing', column: 'photo', files: [{ name: 'a.png', assetId: a.id }, { name: 'b.png', assetId: b.id }] }])
  let calls = 0
  const host = { status: () => ({ ready: true }), processPhoto: async () => { calls++; return pngFromPixels(feathered) } }
  const args = { datasetId: 'ds_processing', sampleAssetId: a.id, recipe: { ...basic, bottom: true }, taskId: 'apply-1' }
  const result = await processing.apply(args, host)
  assert.equal(result.applied, true); assert.equal(calls, 2, '共用同一照片的多条记录只处理一次')
  const ds = require('../electron/dataset.cjs').getDataset(args.datasetId)
  const prepared = photos.prepareRows(ds.id, ['photo'], ds.rows)
  assert.equal(prepared.byRecord.get(ds.rows[0]).photo, result.state.items[a.id], '打印读取同一处理结果')
  assert.equal(prepared.byRecord.get(ds.rows[1]).photo, result.state.items[a.id])
  assert.ok(require('../electron/asset-library.cjs').referencedAssetIds().has(result.state.items[a.id]), '清理素材不能删除仍在使用的处理结果')
  await processing.apply({ ...args, taskId: 'apply-2' }, host)
  assert.equal(calls, 2, '重复应用复用已有结果')
  const before = processing.revision(ds.id)
  const failed = await processing.apply({ ...args, taskId: 'failed', recipe: { ...basic, scale: .9 } }, { processPhoto: async () => { throw Error('示例失败') } })
  assert.equal(failed.applied, false); assert.equal(processing.revision(ds.id), before, '部分失败不能覆盖之前有效的样板')
  let cancelStarted = false
  const canceled = await processing.apply({ ...args, taskId: 'cancel', recipe: { ...basic, scale: .8 } }, { processPhoto: async () => { cancelStarted = true; processing.cancel({ datasetId: ds.id, taskId: 'cancel' }); return pngFromPixels(feathered) } })
  assert.ok(cancelStarted && canceled.canceled); assert.equal(processing.revision(ds.id), before, '取消不能发布半批结果')
  const c = designs.importImageBuffer(pngFromPixels({ width, height, data: contour }), 'c.png', 'managed')
  const bindings = store.loadJson('photo-bindings'); bindings[0].files[0].assetId = c.id; store.saveJson('photo-bindings', bindings)
  assert.throws(() => photos.prepareRows(ds.id, ['photo'], ds.rows), /尚未应用样板/, '照片更换后不能偷偷印原图')
  assert.equal((await photos.preflightRows(ds)).counts.broken, 2, '打印预检明确指出未处理的记录')
  processing.clear(ds.id)
  assert.equal(photos.prepareRows(ds.id, ['photo'], ds.rows).byRecord.get(ds.rows[0]).photo, c.id, '关闭自动处理恢复原照片')
  assert.ok(designs.assetBytes(a.id).buffer.equals(pngFromPixels(image)), '原件字节保持完整')
  console.log('ok - 批量去重、缓存、打印共用、失败/取消隔离、照片更换保护与原件恢复')
  bindings[0].files[0].assetId = a.id; store.saveJson('photo-bindings', bindings)
  await processing.apply({ ...args, taskId: 'restore-batch' }, host)
  const preset = processing.savePreset({ name: '人像柔边', recipe: args.recipe })
  assert.deepEqual(processing.listPresets().find(item => item.id === preset.id).recipe, normalizeRecipe(args.recipe))
  processing.savePreset({ id: preset.id, name: '更新的样板', recipe: basic })
  assert.equal(processing.listPresets().filter(item => item.id === preset.id).length, 1)
  assert.throws(() => processing.savePreset({ name: '', recipe: basic }))
  const individualHost = { processPhoto: async ({ recipe }) => pngFromPixels(processPixels(image, recipe)) }
  const rowId = ds.recordIds[0]
  const single = await processing.setSingle({ datasetId: ds.id, rowId, assetId: a.id, recipe: { ...basic, scale: .65 } }, individualHost)
  const currentDs = require('../electron/dataset.cjs').getDataset(ds.id)
  const individualRows = photos.prepareRows(ds.id, ['photo'], currentDs.rows)
  assert.equal(individualRows.byRecord.get(currentDs.rows[0]).photo, single.asset.id)
  assert.notEqual(individualRows.byRecord.get(currentDs.rows[1]).photo, single.asset.id, '共用同一原图的其他记录不能被单张编辑影响')
  assert.ok(require('../electron/asset-library.cjs').referencedAssetIds().has(single.asset.id))
  assert.ok((await processing.review({ datasetId: ds.id })).rows[0].individual)
  const partial = photos.prepareRows(ds.id, ['photo'], [currentDs.rows[1], currentDs.rows[0]], [1, 0])
  assert.equal(partial.byRecord.get(currentDs.rows[0]).photo, single.asset.id, '选择和重排输出记录后仍按稳定行标识使用单张结果')
  await processing.apply({ ...args, taskId: 'batch-preserve-single' }, host)
  assert.equal(processing.resolver(currentDs)(a.id, rowId), single.asset.id, '重新应用整批样板保留单张例外')
  processing.clearSingle({ datasetId: ds.id, rowId })
  assert.equal(processing.resolver(currentDs)(a.id, rowId), processing.current(ds.id).items[a.id])
  await assert.rejects(processing.setSingle({ datasetId: ds.id, rowId, assetId: b.id, recipe: basic }, individualHost), /更换/)
  processing.setOptions({ datasetId: ds.id, autoProcess: true })
  const beforeAutomatic = calls
  bindings[0].files[0].assetId = c.id; store.saveJson('photo-bindings', bindings)
  processing.scheduleAutomatic(host, () => {}, ds.id)
  for (let i = 0; i < 100 && !processing.current(ds.id).items[c.id]; i++) await new Promise(resolve => setTimeout(resolve, 10))
  assert.ok(processing.current(ds.id).items[c.id], '自动沿用已应用规则处理替换照片')
  assert.equal(calls - beforeAutomatic, 1, '自动处理只重新计算变化的原图')
  assert.equal(processing.resolver(require('../electron/dataset.cjs').getDataset(ds.id))(c.id), processing.current(ds.id).items[c.id])
  processing.setOptions({ datasetId: ds.id, autoProcess: false })
  processing.deletePreset({ id: preset.id })
  assert.ok(!processing.listPresets().some(item => item.id === preset.id))
  console.log('ok - 样板保存复用、单人隔离与重排输出、批量规则保留例外、自动增量处理')
})().catch(error => { console.error(error); process.exitCode = 1 })
