const assert = require('assert/strict'), fs = require('fs'), os = require('os'), path = require('path'), crypto = require('crypto')
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'printpress-audit-'))
process.env.PRINTPRESS_DATA_DIR = root
delete process.env.PRINTPRESS_ASSET_DIR
const { audit } = require('../electron/asset-audit-worker.cjs')
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex')
function put(pool, bytes, claimed = hash(bytes)) {
  const dir = path.join(root, pool); fs.mkdirSync(dir, { recursive: true })
  const name = `${claimed}.png`
  fs.writeFileSync(path.join(dir, name), bytes)
  fs.writeFileSync(path.join(dir, `${claimed}.json`), JSON.stringify({ id: `asset_${claimed}`, path: `${pool}/${name}`, mime: 'image/png' }))
  return claimed
}
;(async () => {
  try {
    const same = Buffer.from('same image bytes'), other = Buffer.from('different image bytes')
    const id = put('design-assets', same); put('photo-assets', same); put('ephemeral-assets', other)
    const before = fs.readdirSync(path.join(root, 'design-assets')).sort()
    const report = await audit()
    assert.equal(report.complete, true)
    assert.equal(report.files, 3)
    assert.equal(report.groups.length, 1)
    assert.equal(report.groups[0].hash, id)
    assert.equal(report.theoreticalBytes, same.length)
    assert.deepEqual(fs.readdirSync(path.join(root, 'design-assets')).sort(), before, '只读扫描不改变文件')
    assert.deepEqual(fs.readFileSync(path.join(root, 'photo-assets', `${id}.png`)), same)
    const assetId = `asset_${id}`, designId = 'design_0123456789abcdef01234567'
    const save = (name, data) => fs.writeFileSync(path.join(root, `${name}.json`), JSON.stringify(data))
    save('asset-library', [{ assetId, displayName: '用户素材' }])
    save('datasets', [{ id: 'ds-a', name: '未打印名单' }])
    save('photo-bindings', [{ datasetId: 'ds-a', files: [{ assetId }] }])
    save('photo-processing-singles', [{ datasetId: 'ds-a', sourceAssetId: assetId, assetId, restoreAssetId: assetId }])
    save('designs', [{ id: designId, revision: 2, name: '示例工程' }])
    save('templates', [{ name: '固定模板', backgroundDesign: { id: designId, revision: 1 } }])
    const project = path.join(root, 'designs', designId); fs.mkdirSync(project, { recursive: true })
    fs.writeFileSync(path.join(project, '1.json'), JSON.stringify({ id: designId, revision: 1, assets: { [assetId]: {} } }))
    fs.writeFileSync(path.join(project, '2.json'), JSON.stringify({ id: designId, revision: 2, assets: {} }))
    save('print-jobs', [{ id: 'job_abc123', templateName: '历史出片', snapshot: 'archive/2026-11/job_abc123/snapshot.html' }])
    const archive = path.join(root, 'archive', '2026-11', 'job_abc123')
    fs.mkdirSync(path.join(archive, 'photos'), { recursive: true })
    fs.writeFileSync(path.join(archive, 'snapshot.html'), '<html></html>')
    fs.writeFileSync(path.join(archive, 'photos', `${id}.png`), same)
    const archiveOnly = Buffer.from('archive-only'), archiveOnlyHash = hash(archiveOnly)
    fs.writeFileSync(path.join(archive, 'photos', `${archiveOnlyHash}.png`), archiveOnly)
    const referenced = await audit(), references = referenced.assets.find(item => item.hash === id).references
    assert.ok(references.some(ref => ref.type === '素材库' && ref.name === '用户素材'))
    assert.ok(references.some(ref => ref.type === '名单照片' && ref.name === '未打印名单'))
    assert.ok(references.some(ref => ref.type === '单人照片修改'))
    assert.ok(references.some(ref => ref.type === '模板固定版本' && ref.name === '固定模板'), '模板固定的历史版本不能漏掉')
    assert.ok(references.some(ref => ref.type === '打印归档独立照片副本' && ref.name === '历史出片'))
    assert.equal(referenced.missingReferences, 0, '独立归档副本不要求素材池保留同一原件')
    assert.equal(referenced.complete, true)
    assert.equal(referenced.noKnownReferences, 1, '未发现引用仅作为待核查统计')
    const badIndex = path.join(root, 'photo-bindings.json')
    fs.writeFileSync(badIndex, '{broken')
    const badReport = await audit()
    assert.equal(badReport.complete, false)
    assert.ok(badReport.issues.some(item => item.pool === 'photo-bindings.json'))
    assert.equal(fs.readFileSync(badIndex, 'utf8'), '{broken', '只读检查不能自动恢复或重命名损坏索引')
    save('photo-bindings', [{ datasetId: 'ds-a', files: [{ assetId }] }])
    put('photo-assets', Buffer.from('corrupt'), hash(other))
    fs.unlinkSync(path.join(root, 'design-assets', `${id}.json`))
    const damaged = await audit()
    assert.equal(damaged.complete, false)
    assert.ok(damaged.issues.some(issue => issue.reason.includes('素材信息')))
    assert.ok(damaged.issues.some(issue => issue.reason.includes('哈希')))
    assert.equal(damaged.groups.length, 1, '哈希不符的副本不得计入重复')
    for (let i = 0; i < 32; i++) put('ephemeral-assets', Buffer.from(`page-${i}`))
    const service = require('../electron/asset-audit.cjs')
    assert.equal(service.start().phase, 'starting')
    await new Promise((resolve, reject) => {
      const deadline = Date.now() + 10000
      const check = () => {
        const state = service.status()
        if (state.phase === 'completed') return resolve()
        if (state.phase === 'failed' || Date.now() > deadline) return reject(Error(JSON.stringify(state)))
        setTimeout(check, 30)
      }; check()
    })
    assert.equal(service.status().report.complete, false)
    assert.equal(service.status().report.assets.total, 34)
    assert.equal(service.status({ assetsPage: 2 }).report.assets.items.length, 4, '素材清单可分页查看')
    assert.equal(service.status({ assetsPage: -1 }).report.assets.page, 1)
    service.start()
    assert.equal((await service.cancel()).phase, 'canceled', '可取消后台扫描')
    console.log('ok - 后台只读核验跨池副本、异常和统计')
  } finally { fs.rmSync(root, { recursive: true, force: true }) }
})().catch(error => { console.error(error); process.exitCode = 1 })
