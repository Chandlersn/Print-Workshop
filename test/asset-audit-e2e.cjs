const { app, BrowserWindow, protocol } = require('electron')
const fs = require('fs'), path = require('path'), assert = require('assert/strict')
const root = path.resolve(__dirname, '..'), tmp = fs.mkdtempSync(path.join(__dirname, '.tmp-audit-e2e-'))
process.env.PRINTPRESS_DATA_DIR = path.join(tmp, 'data')
app.setPath('userData', path.join(tmp, 'userData'))
app.disableHardwareAcceleration()
app.commandLine.appendSwitch('disable-gpu')
app.commandLine.appendSwitch('in-process-gpu')
protocol.registerSchemesAsPrivileged([{ scheme: 'pp', privileges: { standard: true, secure: true, supportFetchAPI: true } }])
app.on('window-all-closed', () => {})
let win
const timeout = setTimeout(() => { console.error('AUDIT_E2E_TIMEOUT'); app.exit(1) }, 45000)
async function wait(expression) {
  for (let i = 0; i < 300; i++) {
    if (await win.webContents.executeJavaScript(expression)) return
    await new Promise(resolve => setTimeout(resolve, 100))
  }
  throw new Error(`等待失败：${expression}`)
}
app.whenReady().then(async () => {
  const designs = require('../electron/designs.cjs')
  const image = fs.readFileSync(path.join(__dirname, 'fixtures/design-portrait.jpg'))
  const source = designs.importImageBuffer(image, 'person.jpg', 'managed')
  designs.importImageBuffer(image, 'person.jpg', 'photo')
  require('../electron/asset-library.cjs').adopt(source.id, { displayName: '引用核验素材' })
  const otherBytes = require('electron').nativeImage.createFromBuffer(image).resize({ width: 20 }).toPNG()
  const other = designs.importImageBuffer(otherBytes, 'unused.png', 'ephemeral')
  const thumbDir = path.join(process.env.PRINTPRESS_DATA_DIR, 'design-thumbnails')
  fs.mkdirSync(thumbDir, { recursive: true })
  const oldThumb = path.join(thumbDir, `${other.id.slice(6)}.png`)
  fs.writeFileSync(oldThumb, Buffer.from('cache'))
  const oldTime = new Date(Date.now() - 8 * 86400000); fs.utimesSync(oldThumb, oldTime, oldTime)
  const lock = require('../electron/data-lock.cjs'); lock.acquireForHost()
  const cleaned = await require('../electron/asset-thumbnail-cleanup.cjs').run()
  assert.equal(cleaned.removed, 1); assert.equal(fs.existsSync(oldThumb), false)
  require('../electron/store.cjs').saveJson('settings', { onboarded: true, demoSeeded: true })
  require('../electron/ipc.cjs').registerIpc()
  require('electron').ipcMain.handle('app:meta', () => ({ version: 'test' }))
  win = new BrowserWindow({ show: false, webPreferences: { preload: path.join(root, 'electron/preload.cjs'), sandbox: false, contextIsolation: true, backgroundThrottling: false } })
  await win.loadFile(path.join(root, 'dist/index.html'))
  await wait(`Boolean([...document.querySelectorAll('.nav-label')].find(el => el.textContent.trim() === '底图制作'))`)
  await win.webContents.executeJavaScript(`[...document.querySelectorAll('.nav-label')].find(el => el.textContent.trim() === '底图制作').click()`)
  await wait(`Boolean(document.querySelector('[data-testid="design-toggle-assets"]'))`)
  await win.webContents.executeJavaScript(`document.querySelector('[data-testid="design-toggle-assets"]').click()`)
  await wait(`Boolean(document.querySelector('[data-testid="asset-audit"]'))`)
  await win.webContents.executeJavaScript(`document.querySelector('[data-testid="asset-audit"]').click()`)
  await wait(`Boolean(document.querySelector('[data-testid="asset-audit-restart"]'))`)
  await win.webContents.executeJavaScript(`document.querySelector('[data-testid="asset-audit-restart"]').click()`)
  await wait(`document.querySelector('[data-testid="asset-audit-panel"]')?.textContent.includes('跨池相同内容 1 组')`)
  const panel = await win.webContents.executeJavaScript(`document.querySelector('[data-testid="asset-audit-panel"]').textContent`)
  assert.ok(panel.includes(source.id.slice(6, 18)))
  assert.ok(panel.includes('不能作为清理依据'))
  assert.ok(panel.includes('素材库：引用核验素材'), '界面展示已知业务引用')
  assert.ok(panel.includes('本次启动已删除 1 个旧缩略图缓存'), '界面报告实际清理结果')
  assert.deepEqual(designs.assetBytes(source.id).buffer, image)
  console.log('AUDIT_E2E_OK')
  clearTimeout(timeout); win.destroy(); lock.release(); try { fs.rmSync(tmp, { recursive: true, force: true }) } catch {} app.exit(0)
}).catch(error => { console.error('AUDIT_E2E_FAIL', error); clearTimeout(timeout); app.exit(1) })
